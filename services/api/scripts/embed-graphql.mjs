// Generates src/graphql/schema-sdl.ts from the contracts package's
// schema.graphql. The SDL is embedded as a string because serverless
// function bundles do not carry untracked files read via fs at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../../packages/contracts/graphql/schema.graphql");
const sdl = readFileSync(source, "utf8");
const out = resolve(here, "../src/graphql/schema-sdl.ts");

writeFileSync(
  out,
  `// GENERATED by scripts/embed-graphql.mjs — do not edit.\n` +
    `// Source: packages/contracts/graphql/schema.graphql\n` +
    `export const SCHEMA_SDL = ${JSON.stringify(sdl)};\n`,
);
console.log(`wrote ${out} (${sdl.length} bytes)`);
